// Props check: builds js/maps/defs/prop_gallery.js headless with the real builder / materials / environment, checks every prop
// (no console errors, no builder warnings, no NaN geometry, colliders present where expected, props rest on the ground) and
// writes a screenshot of every prop type to tools/test/out/props/<type>.png plus row overviews (row-*.png).
// Usage:
//   node tools/test/props.mjs                      everything (q=medium shots)
//   node tools/test/props.mjs --only=car,drum      just these types
//   node tools/test/props.mjs --q=low --noshots    functional checks only (fast)
//   node tools/test/props.mjs --size=1280x720
//   node tools/test/props.mjs --doc               (Node only) rewrite docs/PROPS.md from js/maps/props.js (sizes = real geometry extents)
// Exit code 1 on a console error, a builder warning, a kit with NaN / bad indices, or a prop below the ground.
import { launch, startServer, waitFor, OUT } from './lib.mjs';
import { openPage } from './smoke.mjs';
import fs from 'node:fs'; import path from 'node:path';

const args = process.argv.slice(2);
const flag = k => args.includes('--' + k);
const opt = (k, d) => { const a = args.find(s => s.startsWith('--' + k + '=')); return a ? a.split('=')[1] : d; };
const [W, H] = opt('size', '960x600').split('x').map(Number);
const ONLY = opt('only', '') ? new Set(opt('only', '').split(',')) : null;
const DIR = path.join(OUT, 'props');
const HANGS = new Set(['light_fixture', 'wall_clock']);   // origin = ceiling / wall centre: they hang below y
const frames = async (page, n = 3) => { const f0 = await page.evaluate(() => LF.loop.loopStats.frames); await page.waitForFunction(k => LF.loop.loopStats.frames >= k, f0 + n, { timeout: 120000, polling: 100 }); };

async function writeDoc() {
  const { propList, propSize, RAIL_TOP } = await import('../../js/maps/props.js');
  const f = n => (Math.round(n * 100) / 100).toString().replace(/^0\./, '.');
  const cats = {}; for (const p of propList()) { const c = p.scan ? 'scan' : p.cat; (cats[c] = cats[c] || []).push(p); }
  const TITLE = { industrial: 'Industrial, warehouse, port', construction: 'Construction', military: 'Military', vehicle: 'Vehicles', rail: 'Rail', street: 'Street, barriers, fences',
    nature: 'Nature', interior: 'Interior', scan: 'Poly Haven scans (B.model glb, CC0)' };
  let out = '# LIVE FIRE — prop library\n\nGenerated by `node tools/test/props.mjs --doc` from js/maps/props.js. Place a prop with `B.prop(type, x, y, z, opts)` inside a ' +
    'map\'s `build(B)`. Sizes are w x h x d in metres (x, up, z) of the default variant, measured from the geometry. Conventions, shared options and ' +
    'colliders: docs/ARCHITECTURE.md section 7 (Props). Rail top of a `track`: ' + RAIL_TOP + ' m.\n\n';
  let n = 0;
  for (const c of Object.keys(TITLE)) {
    if (!cats[c]) continue;
    out += '## ' + TITLE[c] + '\n\n';
    for (const p of cats[c]) {
      const sz = propSize(p.type, {}); n++;
      const v = p.variants ? ' Variants: ' + p.variants.map(x => '`' + x + '`').join(' ') + '.' : '';
      const o = Object.keys(p.opts || {}).filter(k => k !== 'variant').map(k => '`' + k + '` ' + p.opts[k]).join('; ');
      const al = p.alias && p.alias.length ? ' (alias ' + p.alias.map(a => '`' + a + '`').join(', ') + ')' : '';
      out += '- `' + p.type + '`' + al + ' — ' + f(sz[0]) + ' x ' + f(sz[1]) + ' x ' + f(sz[2]) + ' m: ' + p.desc + '.' + v + (o ? ' Options: ' + o + '.' : '') + '\n';
    }
    out += '\n';
  }
  fs.writeFileSync(path.join(path.dirname(new URL(import.meta.url).pathname), '../../docs/PROPS.md'), out);
  console.log('docs/PROPS.md: ' + n + ' prop types');
}

async function main() {
  if (flag('doc')) return writeDoc();
  const t0 = Date.now();
  fs.mkdirSync(DIR, { recursive: true });
  const fails = [];
  const check = (cond, msg) => { if (!cond) { fails.push(msg); console.log('  FAIL ' + msg); } else console.log('  ok   ' + msg); };
  // ------------------------------------------------------------------ 1. every kit in Node-like isolation (in the page: no BABYLON needed)
  const srv = await startServer();
  const browser = await launch();
  try {
    const q = opt('q', 'medium');
    const { page, errs } = await openPage(browser, srv.url, '#dev&sandbox&map=prop_gallery&q=' + q + '&nolens&nodyn', { width: W, height: H });
    const warns = [];
    page.on('console', m => { if (m.type() === 'warning') warns.push(m.text()); });
    await waitFor(page, () => (window.LF && LF.sandbox) || document.querySelector('#boot.err'), 600000);
    const bootErr = await page.evaluate(() => { const b = document.querySelector('#boot.err'); return b ? b.textContent : null; });
    if (bootErr) { check(false, 'gallery build: ' + bootErr); throw new Error('boot failed'); }
    await frames(page, 2);
    const info = await page.evaluate(async () => {
      const P = await import('/js/maps/props.js'), G = await import('/js/maps/defs/prop_gallery.js');
      const kits = [];
      for (const p of P.propList()) {
        if (p.scan) continue;
        for (const v of (p.variants || [null])) {
          const o = v ? { variant: v } : {};
          let K = null, err = null;
          try { K = P.propKit(p.type, o); } catch (e) { err = String(e && e.stack || e); }
          if (!K) { kits.push({ type: p.type, v, err }); continue; }
          let nan = 0, bad = 0; for (const g of K.geos.values()) { for (const a of [g.P, g.N, g.U]) for (const x of a) if (!Number.isFinite(x)) nan++; for (const i of g.I) if (i >= g.P.length / 3) bad++; }
          const b = K.bounds();
          kits.push({ type: p.type, v, err, nan, bad, tris: K.tris(), cols: K.cols.length, minY: b.min[1], size: [b.max[0] - b.min[0], b.max[1] - b.min[1], b.max[2] - b.min[2]], decl: P.propSize(p.type, o) });
        }
      }
      const S = LF.sandbox;
      return { kits, stats: S.info.stats, warnings: S.info.warnings, world: S.info.world.stats(), segments: G.SEGMENTS, gallery: G.GALLERY.length, props: P.propList().length,
        hides: S.info.hides.length, scans: P.propList().filter(p => p.scan).map(p => p.type) };
    });
    console.log(`gallery: ${info.props} prop types, ${info.gallery} placements, ${info.world.colliders} colliders, build ${info.stats.msTotal} ms (models ${info.stats.msModels}, meshes ${info.stats.msMeshes}, nav ${info.stats.msNav}), ${info.stats.meshes} meshes, ${info.stats.tris} tris`);
    let tris = 0;
    for (const k of info.kits) {
      if (ONLY && !ONLY.has(k.type)) continue;
      const name = k.type + (k.v ? ':' + k.v : '');
      if (k.err) { check(false, name + ' throws: ' + k.err.split('\n')[0]); continue; }
      tris += k.tris;
      if (k.nan || k.bad) check(false, `${name}: ${k.nan} NaN values, ${k.bad} bad indices`);
      if (k.minY < -0.2 && !HANGS.has(k.type)) check(false, `${name}: geometry ${(-k.minY).toFixed(2)} m below the ground`);
      if (k.size[1] > 0 && k.size[1] < .005) check(false, `${name}: flat geometry`);
    }
    check(info.kits.every(k => !k.err && !k.nan && !k.bad), `all ${info.kits.length} code-built kits build cleanly (${tris} tris in total)`);
    check(!info.warnings.length, 'builder warnings: ' + (info.warnings.length ? info.warnings.join(' | ') : 'none'));
    const propWarn = warns.filter(w => /\[props\]|\[materials\]|\[map /.test(w));
    check(!propWarn.length, 'console warnings from props / materials: ' + (propWarn.length ? propWarn.slice(0, 6).join(' | ') : 'none'));
    // every scan model loaded (B.model warns when a glb fails)
    check(!info.warnings.some(w => /model/.test(w)), 'all ' + info.scans.length + ' Poly Haven scans loaded');
    // ------------------------------------------------------------------ 2. physics: walk the player into a few props (colliders block)
    const phys = await page.evaluate(async () => {
      const S = LF.sandbox, G = (await import('/js/maps/defs/prop_gallery.js')).GALLERY, W = S.info.world, out = [];
      for (const type of ['container', 'car', 'dumpster', 'jersey_barrier', 'crate', 'rack', 'tree', 'sofa', 'hesco', 'fence_chainlink']) {
        const g = G.find(q => q.type === type); if (!g) continue;
        const hit = W.blocked(g.x, .3, g.z, .3, 1.2);
        out.push({ type, blocked: hit });
      }
      const foliage = G.find(q => q.type === 'bush');
      return { out, bushBlocks: foliage ? W.blocked(foliage.x, .2, foliage.z, .3, 1.2) : null };
    });
    for (const p of phys.out) check(p.blocked, 'collider present at the centre of ' + p.type);
    if (phys.bushBlocks !== null) check(!phys.bushBlocks, 'a bush does not block movement (concealment only)');
    // ------------------------------------------------------------------ 3. screenshots
    if (!flag('noshots')) {
      await page.evaluate(() => { for (const s of ['.dbg', '.sbx-help', '.sbx-xh']) { const e = document.querySelector(s); if (e) e.style.display = 'none'; } });
      // one shot per type (variants in chunks of 4): 3/4 view from the front-right, 20 degrees down
      const items = await page.evaluate(() => import('/js/maps/defs/prop_gallery.js').then(m => m.GALLERY.map(g => ({ type: g.type, x: g.x, z: g.z, w: g.w, h: g.h, d: g.d }))));
      const types = [...new Set(items.map(g => g.type))].filter(t => !ONLY || ONLY.has(t));
      for (const type of types) {
        const all = items.filter(g => g.type === type);
        const small = Math.max(...all.map(g => g.h)) < 1.3 && Math.max(...all.map(g => g.w)) < 1.6, per = small ? 3 : 4;
        for (let c = 0; c < all.length; c += per) {
          const part = all.slice(c, c + per);
          const x0 = Math.min(...part.map(g => g.x - Math.max(g.w, 1) / 2)), x1 = Math.max(...part.map(g => g.x + Math.max(g.w, 1) / 2));
          const h = Math.max(...part.map(g => g.h)), d = Math.max(...part.map(g => g.d)), z = part[0].z;
          const fov = .8, pitch = h > 8 ? .22 : .36, yaw = Math.PI - .32;
          const hf = 2 * Math.atan(Math.tan(fov / 2) * W / H), fit = Math.max(x1 - x0 + .4, h * 1.5 * W / H, 1.6);
          const dist = fit / 2 / Math.tan(hf / 2) + d / 2;
          const tx = (x0 + x1) / 2, ty = h * .45, tz = z;
          const fx = Math.sin(yaw) * Math.cos(pitch), fy = -Math.sin(pitch), fz = Math.cos(yaw) * Math.cos(pitch);
          const cam = { x: tx - fx * dist, y: Math.max(.6, ty - fy * dist), z: tz - fz * dist, yaw, pitch, fov };
          // a short far plane culls the rest of the gallery (SwiftShader renders every triangle in view)
          await page.evaluate(([q, far]) => { LF.sandbox.cam(q); LF.sandbox.camera.maxZ = far; }, [cam, dist + Math.max(d, 8) + 12]);
          await frames(page, 3);
          await page.screenshot({ path: path.join(DIR, type + (c ? '-' + (c / per + 1) : '') + '.png') });
        }
      }
      // a few close-ups at eye height (1.64 m) to judge scale against the player
      await page.evaluate(() => { LF.sandbox.camera.maxZ = 150; });
      for (const [type, dz] of [['container', 4], ['car', 3.5], ['sofa', 2.2], ['vending_machine', 2], ['tree', 7], ['hesco', 3]]) {
        const g = (await page.evaluate(t => import('/js/maps/defs/prop_gallery.js').then(m => m.GALLERY.find(q => q.type === t)), type)); if (!g) continue;
        await page.evaluate(c => LF.sandbox.cam(c), { x: g.x + 1.2, y: 1.64, z: g.z + g.d / 2 + dz, yaw: Math.PI - .25, pitch: .05, fov: 1.0 });
        await frames(page, 3); await page.screenshot({ path: path.join(DIR, 'eye-' + type + '.png') });
      }
      const st = await page.evaluate(() => LF.sandbox.stats());
      console.log('  last view: ' + st.drawCalls + ' draw calls, ' + st.tris + ' tris, ' + st.activeMeshes + ' active meshes');
    }
    check(!errs.length, 'zero console errors' + (errs.length ? ': ' + errs.slice(0, 5).join(' | ') : ''));
  } catch (e) {
    fails.push(String(e && e.stack || e)); console.log('  FAIL ' + (e && e.stack || e));
  } finally {
    await browser.close(); srv.stop();
  }
  console.log((fails.length ? 'PROPS FAILED (' + fails.length + ')' : 'PROPS OK') + ' in ' + ((Date.now() - t0) / 1000).toFixed(1) + ' s');
  process.exit(fails.length ? 1 : 0);
}
main();
